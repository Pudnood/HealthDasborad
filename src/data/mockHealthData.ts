import { HealthRecord, AgeGroup, BmiCategory, BpCategory, FbsCategory, RiskLevel } from '../types';

export function calculateBmi(weightKg: number, heightCm: number): number {
  const heightM = heightCm / 100;
  return Number((weightKg / (heightM * heightM)).toFixed(1));
}

export function classifyBmi(bmi: number): BmiCategory {
  if (bmi < 18.5) return 'น้ำหนักน้อย';
  if (bmi <= 22.9) return 'ปกติ';
  if (bmi <= 24.9) return 'น้ำหนักเกิน';
  if (bmi <= 29.9) return 'อ้วนระดับ 1';
  return 'อ้วนระดับ 2 (อันตราย)';
}

export function classifyBp(sbp: number, dbp: number): BpCategory {
  if (sbp >= 160 || dbp >= 100) return 'ความดันสูงขั้น 2 (≥160/≥100)';
  if (sbp >= 140 || dbp >= 90) return 'ความดันสูงขั้น 1 (140-159/90-99)';
  if (sbp >= 120 || dbp >= 80) return 'พรีความดันสูง (120-139/80-89)';
  return 'ปกติ (<120/80)';
}

export function classifyFbs(fbs: number): FbsCategory {
  if (fbs >= 126) return 'สงสัยเป็นเบาหวาน (≥126 mg/dL)';
  if (fbs >= 100) return 'เสี่ยงเบาหวาน IFG (100-125 mg/dL)';
  return 'ปกติ (<100 mg/dL)';
}

export function classifyAgeGroup(age: number): AgeGroup {
  if (age < 35) return '< 35 ปี';
  if (age <= 49) return '35 - 49 ปี';
  if (age <= 59) return '50 - 59 ปี';
  return '60 ปีขึ้นไป';
}

export function determineRiskLevel(
  fbs: number,
  sbp: number,
  dbp: number,
  bmi: number,
  isCentralObese: boolean,
  smoking: string
): RiskLevel {
  if (fbs >= 126 || sbp >= 160 || dbp >= 100 || (fbs >= 120 && sbp >= 140)) {
    return 'กลุ่มป่วย/เสี่ยงสูง';
  }
  if (
    fbs >= 100 ||
    sbp >= 130 ||
    dbp >= 85 ||
    bmi >= 25 ||
    isCentralObese ||
    smoking.includes('สูบ')
  ) {
    return 'กลุ่มเสี่ยง';
  }
  return 'ปกติ';
}

